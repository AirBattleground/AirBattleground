import { useCallback } from "react";
import { defineMessages, useLocale } from "./core";

const enOrdinal = (n: number) => {
  const s = ["th", "st", "nd", "rd"];
  const v = n % 100;
  return `${n}${s[(v - 20) % 10] ?? s[v] ?? s[0]}`;
};

/** "1st" in English/Hinglish; पहला / दूसरा / तीसरा / चौथा / 5वाँ in Hindi. */
export function useOrdinal() {
  const { lang } = useLocale();
  return useCallback(
    (n: number) => {
      if (lang !== "hi") return enOrdinal(n);
      return ({ 1: "पहला", 2: "दूसरा", 3: "तीसरा", 4: "चौथा" } as Record<number, string>)[n] ?? `${n}वाँ`;
    },
    [lang],
  );
}

