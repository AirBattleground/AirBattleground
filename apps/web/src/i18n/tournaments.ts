type Vars = Record<string, string | number>;

/** A translator usable outside React (plain functions like `meChip`). `useT(...)` results satisfy it. */
export type Tr<E extends Record<string, string>> = ((key: keyof E & string, vars?: Vars) => string) & Pick<T<E>, "plural" | "lang">;

const fill = (s: string, vars?: Vars) => (vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`)) : s);

/** Non-hook translator for a fixed language (defaults to English) — for plain helpers called without a hook. */
export function staticT<E extends Record<string, string>>(m: Messages<E>, lang: Language = "en"): Tr<E> {
  const dict = m[lang] as Record<string, string>;
  const en = m.en as Record<string, string>;
  const raw = (key: string) => dict[key] ?? en[key] ?? key;
  const t = ((key: string, vars?: Vars) => fill(raw(key), vars)) as Tr<E>;
  t.plural = ((base: string, count: number, vars?: Vars) => fill(raw(`${base}_${count === 1 ? "one" : "other"}`), { count, ...vars })) as Tr<E>["plural"];
  t.lang = lang;
  return t;
}

/** Rank / choice number: "3rd" in English and Hinglish, "#3" in Hindi. */
export const ordFor = (lang: Language, n: number) => (lang === "hi" ? `#${n}` : ordinal(n));

